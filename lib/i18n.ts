export const DICTS: Record<Lang, Dict> = { fr, en, de };

/**
 * Hook d'accès aux traductions (composants clients uniquement).
 * Retourne la langue courante, la fonction t() et le setter de langue.
 *
 * `t(key, vars?)` accepte un objet de substitution : les segments `{x}` dans
 * la chaîne sont remplacés par `vars.x`. Ex : t("hou.ref", { city: "Berlin" })
 * → "📊 Berlin :".
 */
export function useT(): {
  lang: Lang;
  t: (key: keyof Dict, vars?: Record<string, string>) => string;
  setLang: (lang: Lang) => void;
} {
  const lang = useUiStore((s) => s.lang);
  const setLang = useUiStore((s) => s.setLang);
  return {
    lang,
    t: (key, vars) => {
      const raw = DICTS[lang][key] ?? DICTS.fr[key] ?? "";
      if (!vars) return raw;
      return raw.replace(/\{(\w+)\}/g, (_, k) =>
        Object.prototype.hasOwnProperty.call(vars, k) ? String(vars[k]) : `{${k}}`
      );
    },
    setLang,
  };
}

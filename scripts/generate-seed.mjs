/** Convertit "JJ/MM/AAAA" en timestamp ISO (coup d'envoi 20h00 heure de Paris ≈ 18h00 UTC) */
function toIsoDate(dmy) {
  const [d, m, y] = dmy.split("/").map(Number);
  const dd = String(d).padStart(2, "0");
  const mm = String(m).padStart(2, "0");
  return `${y}-${mm}-${dd} 18:00:00+00`;
}

function esc(s) {
  return s.replace(/'/g, "''");
}

